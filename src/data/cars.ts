export function getCarById(id: string): Car | undefined {
  return cars.find((car) => car.id === id);
}

export function getFeaturedCars(): Car[] {
  return cars.filter((car) => car.featured);
}

export function getMakes(): string[] {
  return [...new Set(cars.map((car) => car.make))].sort();
}

export function getModelsForMake(make?: string): string[] {
  const filtered = make
    ? cars.filter((car) => car.make.toLowerCase() === make.toLowerCase())
    : cars;
  return [...new Set(filtered.map((car) => car.model))].sort();
}

export function getLocations(): string[] {
  return [...new Set(cars.map((car) => car.location))].sort();
}
